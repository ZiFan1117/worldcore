//! Agent 运行时（**世界核心「管」那一层在执行侧的那一半**）。
//!
//! ## 它为什么在世界核心里，而不是仓根的一个独立程序
//!
//! 作者的裁定（2026-09-28，逐字）：「**world-core 应该有 agentd**」／
//! 「**agentd 属世界核心**」／「**这个 Agent 必须使用 rust 写，而且它必须属于这个 world core**」
//! ＋「**agentd 和其他内容一样归纳到相应代码位置**」。
//! ⇒ **同 crate 模块**：落 `src/**`，与既有核心代码同构；
//! 仓根那套 Go **不再作为独立组件**（其能力面归入相应模块，旧件随 git 历史留存）。
//!
//! ## 它与 `crate::carrier`（`M10`）的分工（**读之前先读这一段**）
//!
//! 载体适配器（`M10`，即 `crate::carrier`）是**手**：只执行、不裁决。
//! 本模块是**这只手在长活儿与留痕上的那几件工具**。
//!
//! | 能力面 | 落点 | 状态 |
//! |---|---|---|
//! | 能力声明解析、风险／撤销／确认三栏 | `crate::carrier::capd` | **已有**（不重写） |
//! | 执行器契约与内置执行器 | `crate::carrier::provider`／`crate::carrier::providers` | **已有**（不重写） |
//! | 处置顺序（清单 → 动词 → 确认 → 撤销点 → 执行） | `crate::carrier::providers::execute` | **已有**（不重写） |
//! | 问内核 → 执行 → 报结果 | `crate::carrier::run` | **已有**（不重写） |
//! | **结构化审计留痕** | [`audit`] | **本模块新增** |
//!
//! ## 一条**不许违反**的口径（本项目已裁定，写在 M10 的代码里）
//!
//! 旧 Go 实现在载体侧**自己维护一本完工铃登记簿**（落盘、重启后标记"丢了"）。
//! 本项目**明确拒绝**那本登记簿：「哪些活还没干完」由**账本折叠**回答，
//! 否则「待办清单」会成为**第二份真相**。逐字见
//! `crate::carrier::recover` 与 `crate::carrier::providers::Job` 两处的头注。
//! ⇒ 本模块**SHALL NOT** 引入任何"登记簿"文件。

